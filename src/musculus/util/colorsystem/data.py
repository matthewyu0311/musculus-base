def standard_illuminants_a_spd(wavelength: float) -> float:
    """Returns the relative spectral power distribution of Standard Illuminant A at a given wavelength.
    The value at 560 nm is 100.
    The value for Standard Illuminant A is calculated from the specified standard formula.
    """
    return (
        STANDARD_ILLUMINANT_A_COEFFICIENT
        * (STANDARD_ILLUMINANT_NORMALIZE_WAVELENGTH / wavelength) ** 5
        / (
            exp(
                SECOND_RADIATION_CONSTANT_NM_1931
                / (STANDARD_ILLUMINANT_A_CCT_1931 * wavelength)
            )
            - 1
        )
    )


