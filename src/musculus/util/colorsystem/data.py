def precision_to_fmt(precision: int | None):
    if precision is not None:
        return f"%.{precision}f"
    return None


def tidify_float(
    values: float,
    /,
    *,
    ensure_positive: bool = False,
    fmt: str | None = None,
) -> float:
    if ensure_positive and not values > 0.0:
        return 0.0
    elif fmt is not None:
        return float(fmt % values)
    else:
        return float(values)


def deconvolve_table[Row: tuple[float, ...]](
    table: Mapping[float, Row],
    factor: float = 0.1,
) -> dict[float, Row]:
    """
    Implements deconvolution, which makes "the data more like those that would have been obtained with a 1 nm window." (Hunt 1991:179)
    For details, see Hunt (1991) Measuring Colour, 2nd ed. Chichester: Ellis Horwood.

    NOTE: Whether to perform deconvolution and what factor to use are matters of practical judgement.
    Deconvolution is sometimes used on empirically-measured spectra prior to interpolation.
    Standard table entries, such as those provided in this module, are typically used or interpolated as-is without deconvolution.
    """
    output = {}
    wavelengths = list(table.keys())
    for i, (wavelength, row) in enumerate(table.items()):
        if i > 0:
            last_row = table[wavelengths[i - 1]]
        else:
            last_row = row
        try:
            next_row = table[wavelengths[i + 1]]
        except IndexError:
            next_row = row
        output[wavelength] = cast(
            Row,
            tuple(
                b + factor * (2 * b - a - c) for a, b, c in zip(last_row, row, next_row)
            ),
        )
    return output


def make_interpolator_from_scipy[Row: tuple[float, ...]](
    table: Mapping[float, Row],
    interpolator_factory: SciPyInterpolatorFactory[Row],
    /,
    *args,
    ensure_positive: bool = False,
    tidify_fmt: str | None = None,
    **kwargs,
) -> Interpolator[Row]:
    """
    NOTE: Which interpolation method to use is a matter of practical judgement.
    Is cubic spline, Akima, PCHIP necessarily "better" than linear interpolation or nearest value for a given set of data?
    """
    wavelengths_table = list(table.keys())
    values_table = list(table.values())
    scipy_interpolator = interpolator_factory(
        wavelengths_table, values_table, *args, **kwargs
    )
    return lambda wavelength: cast(
        Row,
        tuple(
            tidify_float(x, ensure_positive=ensure_positive, fmt=tidify_fmt)
            for x in scipy_interpolator(wavelength)
        ),
    )


def make_linear_interpolator[Row: tuple[float, ...]](
    table: Mapping[float, Row],
    *,
    extrapolate: bool = False,
    integer_interval: int | None = None,
) -> Interpolator[Row]:
    """Makes a linear interpolator from a table.
    The keys need not be in ascending order or have regular intervals.

    NOTE: Which interpolation method to use is a matter of practical judgement.
    """
    # Sort the wavelengths ahead of interpolation
    table_wavelengths = list(table.keys())
    table_wavelengths.sort()

    shortest_wavelength = table_wavelengths[0]
    longest_wavelength = table_wavelengths[-1]
    cols = len(table[shortest_wavelength])
    zero_row = cast(Row, (0.0,) * cols)

    def interpolate(wavelength: float):
        try:
            # Fast path
            return table[wavelength]
        except KeyError:
            pass
        if wavelength < shortest_wavelength:
            if not extrapolate:
                return zero_row
            try:
                wavelengthA = table_wavelengths[0]
                wavelengthB = table_wavelengths[1]
            except IndexError:
                return table[shortest_wavelength]
        elif wavelength > longest_wavelength:
            if not extrapolate:
                return zero_row
            try:
                wavelengthA = table_wavelengths[-2]
                wavelengthB = table_wavelengths[-1]
            except IndexError:
                return table[longest_wavelength]
        else:
            if integer_interval:
                # This ONLY works for regular integer intervals (otherwise you'll have floating point errors)
                n = int((wavelength - shortest_wavelength) // integer_interval)
            else:
                # Use binary search to avoid issues caused by floating-point errors, irregularly-spaced tables, etc.
                # (Table with wavelengths at 0.1 nm intervals? Good luck doing floating-point division with that!)
                n = bisect_right(table_wavelengths, wavelength) - 1
                assert n >= 0
            wavelengthA = table_wavelengths[n]
            wavelengthB = table_wavelengths[n + 1]
        factorB = (wavelength - wavelengthA) / (wavelengthB - wavelengthA)
        factorA = 1 - factorB
        return cast(
            Row,
            tuple(
                a * factorA + b * factorB
                for a, b in zip(table[wavelengthA], table[wavelengthB], strict=True)
            ),
        )

    return interpolate


def interpolate_table[Row: tuple[float, ...]](
    interpolator: Interpolator[Row],
    start_wavelength: float = 360,
    end_wavelength: float = 830,
    interval: float = 1.0,
) -> dict[float, Row]:
    count = int((end_wavelength - start_wavelength) // interval + 1)
    wavelengths = [i * interval + start_wavelength for i in range(count)]
    return {
        wavelength: cast(Row, tuple(interpolator(wavelength)))
        for wavelength in wavelengths
    }


def c_literal(
    table: WavelengthTable, *, indent: str | int = 4, fmt: str = "%.4f"
) -> str:
    """Makes C / C++ / Java brace-enclosed literal from a table."""
    row_strings = ["{"]
    if isinstance(indent, int):
        indent = " " * indent
    for k, v in table.items():
        row_strings.append(
            indent
            + "{"
            + f"{", ".join(map(lambda x: fmt % x, v))}"
            + "},  "
            + f"// {k!s} nm"
        )
    row_strings.append("};")
    return "\n".join(row_strings)


